#!/usr/bin/env node
/*
 * Extract the PGM cases from samples/closed-loop-motion-cases.zip and emit
 * src/samples.generated.js so the bench opens with real data.
 *
 * The zip's local file headers carry the sizes (no data descriptors), so a
 * minimal reader plus zlib.inflateRawSync is enough; no dependencies.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const root = path.join(__dirname, '..');
const zipPath = path.join(root, 'samples', 'closed-loop-motion-cases.zip');
const outPath = path.join(root, 'src', 'samples.generated.js');

function readZip(buf) {
  const entries = new Map();
  let p = 0;
  while (p + 30 <= buf.length && buf.readUInt32LE(p) === 0x04034b50) {
    const method = buf.readUInt16LE(p + 8);
    const csize = buf.readUInt32LE(p + 18);
    const nlen = buf.readUInt16LE(p + 26);
    const elen = buf.readUInt16LE(p + 28);
    const name = buf.subarray(p + 30, p + 30 + nlen).toString('utf8');
    const dataStart = p + 30 + nlen + elen;
    const raw = buf.subarray(dataStart, dataStart + csize);
    if (method === 0) entries.set(name, raw);
    else if (method === 8) entries.set(name, zlib.inflateRawSync(raw));
    else throw new Error(`unsupported compression method ${method} for ${name}`);
    p = dataStart + csize;
  }
  return entries;
}

function parsePGM(bytes, name) {
  const text = Buffer.from(bytes).toString('latin1');
  const m = /^P5\s+(?:#[^\n]*\n\s*)*(\d+)\s+(\d+)\s+(\d+)\s/.exec(text);
  if (!m) throw new Error(`cannot parse ${name}`);
  const width = Number(m[1]);
  const height = Number(m[2]);
  const maxval = Number(m[3]);
  if (maxval !== 255) throw new Error(`${name}: maxval ${maxval}`);
  let headerBytes = m[0].length;
  if (bytes[headerBytes - 1] === 0x0d && bytes[headerBytes] === 0x0a) headerBytes += 1;
  const raster = bytes.subarray(headerBytes, headerBytes + width * height);
  if (raster.length !== width * height) throw new Error(`${name}: short raster`);
  return { name, width, height, raster };
}

const zip = readZip(fs.readFileSync(zipPath));
const groups = new Map();
for (const [name, bytes] of zip) {
  if (!/\.pgm$/i.test(name)) continue;
  const parts = name.split('/');
  const file = parts.pop();
  const group = parts.join('/') || 'root';
  const frame = /(\d+)\.pgm$/i.exec(file);
  if (!frame) continue;
  if (!groups.has(group)) groups.set(group, []);
  groups.get(group).push({ number: Number(frame[1]), pgm: parsePGM(bytes, name) });
}

const samples = {};
for (const [group, list] of groups) {
  list.sort((a, b) => a.number - b.number);
  list.forEach((item, i) => {
    if (item.number !== i) throw new Error(`${group}: frame numbering gap at ${i}`);
  });
  const { width, height } = list[0].pgm;
  samples[group] = {
    width,
    height,
    frames: list.map(item => Buffer.from(item.pgm.raster).toString('base64')),
  };
}

const body = `/* Generated by tools/extract_samples.js from samples/closed-loop-motion-cases.zip.
 * Do not edit; re-run the script instead. */
window.MVR1_SAMPLES = ${JSON.stringify(samples, null, 2)};
`;
fs.writeFileSync(outPath, body);
for (const [group, s] of Object.entries(samples)) {
  console.log(`${group}: ${s.width}x${s.height}, ${s.frames.length} frames`);
}
console.log('wrote', path.relative(root, outPath));
