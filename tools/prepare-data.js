#!/usr/bin/env node
/*
 * Bundle the sample cases.
 *   - small cases are inlined into src/samples-inline.js so the page always
 *     opens with real data, even from file://
 *   - large cases are written to data/samples/<id>.json and fetched on demand
 *   - data/samples/index.json lists every case
 */
'use strict';
const fs = require('fs');
const path = require('path');

const srcDir = process.argv[2] || path.join(__dirname, '..', 'samples', 'extracted');
const root = path.join(__dirname, '..');
const outDir = path.join(root, 'data', 'samples');
const inlineFile = path.join(root, 'src', 'samples-inline.js');

const INLINE_LIMIT = 40 * 1024;

const MANIFEST = [
  ['sharp-box', '尖锐立方', 'Sharp box'],
  ['sphere', '球面', 'Sphere'],
  ['open-plane', '开放平面', 'Open plane'],
  ['checkerboard', '棋盘', 'Checkerboard'],
  ['skew-cell', '斜切单元', 'Skew cell'],
  ['anisotropic', '各向异性', 'Anisotropic'],
  ['limit-sphere', '高密度球', 'Limit sphere'],
  ['inverted-sphere', '反相球', 'Inverted sphere'],
  ['rank-one', '秩一平面', 'Rank one'],
  ['empty', '全同号空结果', 'All same sign'],
  ['invalid-missing-edge', '缺边（错误样例）', 'Missing edge'],
  ['invalid-duplicate-edge', '重复边（错误样例）', 'Duplicate edge'],
  ['invalid-zero-normal', '零法线（错误样例）', 'Zero normal'],
  ['invalid-zero-sign', '非法符号（错误样例）', 'Zero sign'],
];

const inline = [];
const index = [];
fs.mkdirSync(outDir, { recursive: true });

for (const [id, name, nameEn] of MANIFEST) {
  const p = path.join(srcDir, id + '.json');
  if (!fs.existsSync(p)) {
    console.warn('missing', p);
    continue;
  }
  const text = fs.readFileSync(p, 'utf8');
  const bytes = Buffer.byteLength(text);
  const raw = JSON.parse(text);
  const entry = { id, name, nameEn, file: 'data/samples/' + id + '.json', bytes };
  if (bytes <= INLINE_LIMIT) {
    inline.push({ id, name, nameEn, raw });
    entry.inline = true;
  } else {
    fs.writeFileSync(path.join(outDir, id + '.json'), text);
    entry.inline = false;
  }
  index.push(entry);
}

fs.writeFileSync(path.join(root, 'data', 'samples', 'index.json'), JSON.stringify({ cases: index }, null, 1));

const banner = '/* Generated by tools/prepare-data.js — do not edit by hand. */\n';
const body = 'window.BHE_INLINE_SAMPLES = ' + JSON.stringify(inline) + ';\n';
fs.writeFileSync(inlineFile, banner + body);

console.log('index:', index.length, 'cases;', inline.length, 'inline;', index.length - inline.length, 'on disk');
for (const e of index) console.log('  ', e.id.padEnd(24), e.inline ? 'inline' : 'file  ', (e.bytes / 1024).toFixed(1) + ' KiB');
