// Generate a synthetic case bundle for load/scale testing.
// Usage: node tools/make-case.mjs <out.zip> [--M 8 --P 8 --Q 2 --hlen 4096 --tlen 4096 --taps 4096 --delay 4095 --lambda 0.05 --limit 0.001 --seed 7 --rank}
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { zip } = require('../src/inflate.js');
const core = require('../src/core.js');

function arg(name, defv) {
  const i = process.argv.indexOf(`--${name}`);
  if (i < 0) return defv;
  const v = process.argv[i + 1];
  return v === undefined || v.startsWith('--') ? true : v;
}

const out = process.argv[2];
if (!out || out.startsWith('--')) {
  console.error('usage: node tools/make-case.mjs <out.zip> [options]');
  process.exit(2);
}
const M = Number(arg('M', 8));
const P = Number(arg('P', 8));
const Q = Number(arg('Q', 2));
const hlen = Number(arg('hlen', 4096));
const tlen = Number(arg('tlen', 4096));
const taps = Number(arg('taps', 4096));
const delay = Number(arg('delay', 4095));
const lambda = Number(arg('lambda', 0.05));
const limit = Number(arg('limit', 0.001));
const seed0 = Number(arg('seed', 7));
const rankDef = !!arg('rank', false);
const weightArg = arg('weight', null);
const weights = weightArg == null ? Array(M).fill(4) : String(weightArg).split(',').map(Number);

let seed = seed0 >>> 0;
const rnd = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296; };
const rn = () => { let u = 0, v = 0; while (u === 0) u = rnd(); while (v === 0) v = rnd(); return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v); };

// choose per-path L1 so the weighted energy stays just under 16
let wsum = 0;
for (const w of weights) wsum += w;
const l1per = Math.sqrt(15.5 / (wsum * P)) * 0.99;

const h_lengths = [], t_lengths = [];
const H = [], T = [];
for (let m = 0; m < M; m++) {
  H.push([]); h_lengths.push([]);
  for (let p = 0; p < P; p++) {
    const h = new Float64Array(hlen);
    const dup = rankDef && p > 0;
    if (dup) h.set(H[m][0]);
    else {
      let acc = 0;
      for (let n = 0; n < hlen; n++) { acc = 0.98 * acc + rn() * 0.1; h[n] = acc * Math.exp(-n / 900); }
      let s1 = 0; for (let n = 0; n < hlen; n++) s1 += Math.abs(h[n]);
      const sc = l1per / s1;
      for (let n = 0; n < hlen; n++) h[n] *= sc;
    }
    H[m].push(h); h_lengths[m].push(hlen);
  }
}
for (let m = 0; m < M; m++) {
  T.push([]); t_lengths.push([]);
  for (let q = 0; q < Q; q++) {
    const t = new Float64Array(tlen);
    for (let n = 0; n < tlen; n++) t[n] = 0.02 * rn() * Math.exp(-n / 1500);
    T[m].push(t); t_lengths[m].push(tlen);
  }
}
let total = 0;
for (const row of h_lengths) for (const l of row) total += l;
for (const row of t_lengths) for (const l of row) total += l;
const buf = new ArrayBuffer(total * 4);
const dv = new DataView(buf);
let off = 0;
const put = (v) => { dv.setFloat32(off, v, true); off += 4; };
for (let m = 0; m < M; m++) for (let p = 0; p < P; p++) for (const v of H[m][p]) put(v);
for (let m = 0; m < M; m++) for (let q = 0; q < Q; q++) for (const v of T[m][q]) put(v);

const project = {
  weights, limits: Array(P).fill(limit), h_lengths, t_lengths, lambda, delay, taps,
};
const enc = new TextEncoder();
const zipBytes = zip([
  { name: 'project.json', data: enc.encode(JSON.stringify(project)) },
  { name: 'signals.f32', data: new Uint8Array(buf) },
  { name: '约定.txt', data: enc.encode('synthetic case generated by tools/make-case.mjs\n') },
]);
fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true });
fs.writeFileSync(out, zipBytes);
const energy = core.energyTerms(H, weights);
console.log(`wrote ${out}: M=${M} P=${P} Q=${Q} samples=${total} energy=${energy.total.toFixed(3)} bytes=${zipBytes.length}`);
