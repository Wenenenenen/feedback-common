// Build src/worker-source.js: the numeric core + report pipeline as a single
// string, so a Blob worker can be created even when the page is opened from
// file:// (where same-directory worker scripts are blocked by origin rules).
//
// Usage: node tools/build-worker.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const files = ['src/core.js', 'src/report.js'];
const glue = `
/* worker glue (generated) */
(function () {
  'use strict';
  // At most one solve runs at a time. A newer request supersedes a running
  // one: the runner is asked to abort at its next yield and the replacement
  // starts as soon as it has unwound. A cancelled or superseded solve never
  // posts a result.
  var activeToken = 0;
  var running = false;
  var queued = null;

  function startSolve(msg) {
    var reqId = msg.reqId;
    var token = reqId;
    activeToken = token;
    running = true;
    var post = function (payload, transfer) {
      if (activeToken !== token) return;
      self.postMessage(Object.assign({ reqId: reqId }, payload), transfer || []);
    };
    var done = function () {
      running = false;
      if (queued) {
        var next = queued;
        queued = null;
        startSolve(next);
      }
    };
    self.AIReport.runSolve(msg.cfg, {
      onEvent: function (ev) {
        if (activeToken !== token) return;
        post({ type: 'progress', event: ev });
      },
      shouldAbort: function () { return activeToken !== token; }
    }).then(function (report) {
      if (activeToken !== token) { done(); return; }
      if (report.aborted) { post({ type: 'aborted' }); done(); return; }
      var transfer = self.AIReport.transferables(report);
      post({ type: 'result', report: report }, transfer);
      activeToken = 0;
      done();
    }).catch(function (err) {
      if (activeToken === token) {
        post({ type: 'error', message: err && err.message ? err.message : String(err) });
        activeToken = 0;
      }
      done();
    });
  }

  self.onmessage = function (e) {
    var msg = e.data || {};
    if (msg.type === 'cancel') {
      if (activeToken === msg.token) activeToken = 0;
      if (queued && queued.reqId === msg.token) queued = null;
      return;
    }
    if (msg.type !== 'solve') return;
    if (running) {
      // supersede: drop whatever was queued and let this one take over
      queued = msg;
      activeToken = 0;
      return;
    }
    startSolve(msg);
  };
})();
`;

let bundle = '';
for (const rel of files) {
  const p = path.join(root, rel);
  let text = fs.readFileSync(p, 'utf8');
  // Neutralise an accidental closing tag if one is ever added to the source.
  text = text.replace(/<\/script/gi, '<\\/script');
  bundle += `/* ==== ${rel} ==== */\n${text}\n`;
}
bundle += glue;

const out = path.join(root, 'src/worker-source.js');
const body = `/* AUTO-GENERATED by tools/build-worker.mjs — do not edit by hand. */
window.AI_WORKER_SOURCE = ${JSON.stringify(bundle)};
`;
const existing = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
if (process.argv.includes('--check')) {
  if (existing !== body) {
    console.error('worker-source.js is stale; run: node tools/build-worker.mjs');
    process.exit(1);
  }
  console.log('worker-source.js is up to date');
} else {
  fs.writeFileSync(out, body);
  console.log(`wrote ${path.relative(root, out)} (${(body.length / 1024).toFixed(1)} KiB)`);
}
