// 生成 src/js/worker-source.js：把 fft.js + core.js + worker-glue.js 拼成一个
// 字符串，供 Blob Worker 使用（file:// 打开时同目录 Worker 脚本会被同源策略拦）。
//
// 用法：node tools/build-worker.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const files = ['src/js/fft.js', 'src/js/core.js', 'src/worker-glue.js'];

let bundle = '';
for (const rel of files) {
  const p = path.join(root, rel);
  let text = fs.readFileSync(p, 'utf8');
  // 防止意外出现 </script 提前结束内联脚本
  text = text.replace(/<\/script/gi, '<\\/script');
  bundle += `/* ==== ${rel} ==== */\n${text}\n`;
}

const body = `/* AUTO-GENERATED by tools/build-worker.mjs — do not edit by hand. */
(function () {
  'use strict';
  var src = ${JSON.stringify(bundle)};
  window.SHM_WORKER_SOURCE = src;
  window.SHM_makeWorker = function () {
    return new Worker(URL.createObjectURL(new Blob([src], { type: 'text/javascript' })));
  };
})();
`;
const out = path.join(root, 'src/js/worker-source.js');
const existing = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
if (process.argv.includes('--check')) {
  if (existing !== body) {
    console.error('worker-source.js 已过期；请运行：node tools/build-worker.mjs');
    process.exit(1);
  }
  console.log('worker-source.js 是最新的');
} else {
  fs.writeFileSync(out, body);
  console.log(`wrote ${path.relative(root, out)} (${(body.length / 1024).toFixed(1)} KiB)`);
}
