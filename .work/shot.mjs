import { chromium } from 'playwright';
import { createServer } from 'node:http';
import { readFileSync, createReadStream, existsSync } from 'node:fs';
import { extname, join, normalize } from 'node:path';
const ROOT = process.cwd(); const SAMPLES = join(ROOT,'.work/samples-extract');
const MIME={'.html':'text/html','.js':'text/javascript','.css':'text/css','.json':'application/json'};
const server=createServer((req,res)=>{let p=decodeURIComponent(req.url.split('?')[0]);let f=p.startsWith('/samples/')?join(SAMPLES,p.slice(9)):join(ROOT,'src',normalize(p).replace(/^(\.\.[/\\])+/,''));if(existsSync(f)){res.setHeader('Content-Type',MIME[extname(f)]||'application/octet-stream');createReadStream(f).pipe(res);}else{res.statusCode=404;res.end();}});
await new Promise(r=>server.listen(0,r));
const b=await chromium.launch(); const page=await b.newPage({viewport:{width:1400,height:900}});
await page.goto(`http://localhost:${server.address().port}/index.html`,{waitUntil:'networkidle'});
const up=async (id,name)=>page.setInputFiles(`#${id}`,{name,mimeType:'application/json',buffer:readFileSync(join(SAMPLES,name))});
await up('fileInput','disconnected.json');
await page.waitForFunction(()=>document.querySelector('#diagBox').textContent.includes('求解耗时'));
await page.waitForTimeout(300);
await page.screenshot({path:'.work/shot-disconnected.png'});
await up('fileInput','flat.json');
await page.waitForFunction(()=>document.querySelector('#diagBox').textContent.includes('求解耗时'));
await page.check('#multiMode');
await page.evaluate(()=>window.__pickIsolated(22));
await page.evaluate(()=>window.__pickIsolated(58));
await page.waitForTimeout(300);
await page.screenshot({path:'.work/shot-multisource.png'});
await b.close(); server.close(); console.log('shots done');
